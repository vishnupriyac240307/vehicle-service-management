PROMPT 4. VERIFICATION: 3-TABLE JOIN REPORT
PROMPT ------------------------------------------------------------------------

COLUMN customer_name FORMAT A15
COLUMN vehicle_number FORMAT A12
COLUMN vehicle_model FORMAT A25
COLUMN service_date FORMAT A12
COLUMN service_type FORMAT A16
COLUMN service_status FORMAT A10
COLUMN service_cost FORMAT 99,999.99

SELECT 
    c.customer_name,
    v.vehicle_number,
    v.vehicle_model,
    TO_CHAR(s.service_date, 'YYYY-MM-DD') AS service_date,
    s.service_type,
    s.service_status,
    s.service_cost
FROM CUSTOMER c
JOIN VEHICLE v ON c.customer_id = v.customer_id
JOIN SERVICE s ON v.vehicle_id = s.vehicle_id
ORDER BY s.service_date DESC;

