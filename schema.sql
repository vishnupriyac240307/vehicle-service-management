-- ============================================================================
-- 1. TABLE: CUSTOMER
-- Description: Stores customer personal and contact information.
-- Relationships: One customer can own multiple vehicles (1 : M).
-- ============================================================================
CREATE TABLE CUSTOMER (
    customer_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_name   VARCHAR2(100) NOT NULL,
    contact_number  VARCHAR2(20)  NOT NULL,
    email           VARCHAR2(100) NOT NULL,
    address         VARCHAR2(255),
    CONSTRAINT pk_customer PRIMARY KEY (customer_id),
    CONSTRAINT uq_customer_email UNIQUE (email)
);

COMMENT ON TABLE CUSTOMER IS 'Stores vehicle owner / customer profile details';
COMMENT ON COLUMN CUSTOMER.customer_id IS 'Auto-generated unique primary key identifier for each customer';
COMMENT ON COLUMN CUSTOMER.customer_name IS 'Full name of the customer (Required)';
COMMENT ON COLUMN CUSTOMER.contact_number IS 'Primary phone/contact number (Required)';
COMMENT ON COLUMN CUSTOMER.email IS 'Unique email address of customer for communication';
COMMENT ON COLUMN CUSTOMER.address IS 'Residential or business address of customer';

-- ============================================================================
-- 2. TABLE: VEHICLE
-- Description: Stores vehicle details linked to a registered customer.
-- Relationships: 
--   - Each vehicle belongs to one existing customer (M : 1).
--   - One vehicle can have multiple service records (1 : M).
-- ============================================================================
CREATE TABLE VEHICLE (
    vehicle_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    vehicle_number  VARCHAR2(20)  NOT NULL,
    vehicle_type    VARCHAR2(50)  NOT NULL,
    vehicle_model   VARCHAR2(100) NOT NULL,
    customer_id     NUMBER        NOT NULL,
    CONSTRAINT pk_vehicle PRIMARY KEY (vehicle_id),
    CONSTRAINT uq_vehicle_number UNIQUE (vehicle_number),
    CONSTRAINT fk_vehicle_customer FOREIGN KEY (customer_id) 
        REFERENCES CUSTOMER (customer_id)
);

COMMENT ON TABLE VEHICLE IS 'Stores registered vehicles linked to owners';
COMMENT ON COLUMN VEHICLE.vehicle_id IS 'Auto-generated unique primary key identifier for each vehicle';
COMMENT ON COLUMN VEHICLE.vehicle_number IS 'Unique vehicle registration / license plate number (e.g. TN38AB1234)';
COMMENT ON COLUMN VEHICLE.vehicle_type IS 'Category of vehicle (Car, Bike, SUV, etc.)';
COMMENT ON COLUMN VEHICLE.vehicle_model IS 'Manufacturer model description (e.g. Hyundai i20)';
COMMENT ON COLUMN VEHICLE.customer_id IS 'Foreign key referencing CUSTOMER(customer_id)';

-- ============================================================================
-- 3. TABLE: SERVICE
-- Description: Stores individual service work orders, dates, status, and cost.
-- Relationships: Each service record belongs to one existing vehicle (M : 1).
-- Constraints:
--   - service_cost must be zero or greater (CHECK constraint).
--   - service_status must be either 'Pending' or 'Completed' (CHECK constraint).
-- ============================================================================
CREATE TABLE SERVICE (
    service_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    vehicle_id      NUMBER         NOT NULL,
    service_date    DATE           NOT NULL,
    service_type    VARCHAR2(50)   NOT NULL,
    service_status  VARCHAR2(20)   NOT NULL,
    service_cost    NUMBER(10, 2)  NOT NULL,
    CONSTRAINT pk_service PRIMARY KEY (service_id),
    CONSTRAINT fk_service_vehicle FOREIGN KEY (vehicle_id) 
        REFERENCES VEHICLE (vehicle_id),
    CONSTRAINT chk_service_status CHECK (service_status IN ('Pending', 'Completed')),
    CONSTRAINT chk_service_cost CHECK (service_cost >= 0)
);

COMMENT ON TABLE SERVICE IS 'Tracks maintenance and service orders for vehicles';
COMMENT ON COLUMN SERVICE.service_id IS 'Auto-generated unique primary key identifier for each service record';
COMMENT ON COLUMN SERVICE.vehicle_id IS 'Foreign key referencing VEHICLE(vehicle_id)';
COMMENT ON COLUMN SERVICE.service_date IS 'Date when service is scheduled or performed';
COMMENT ON COLUMN SERVICE.service_type IS 'Type of service provided (General Service, Oil Change, etc.)';
COMMENT ON COLUMN SERVICE.service_status IS 'Current status: Pending or Completed';
COMMENT ON COLUMN SERVICE.service_cost IS 'Cost of service in INR (must be >= 0)';

-- Create indexes on Foreign Keys for query optimization (DBA best practice)
CREATE INDEX idx_vehicle_customer ON VEHICLE(customer_id);
CREATE INDEX idx_service_vehicle ON SERVICE(vehicle_id);
CREATE INDEX idx_service_date ON SERVICE(service_date);
CREATE INDEX idx_service_status ON SERVICE(service_status);

