-- ============================================================================
-- SECTION D: FILTERING AND SORTING
-- ============================================================================

-- D1. Retrieve services with 'Pending' status
SELECT 
    s.service_id, 
    v.vehicle_number, 
    s.service_type, 
    TO_CHAR(s.service_date, 'YYYY-MM-DD') AS service_date, 
    s.service_status, 
    s.service_cost
FROM SERVICE s
JOIN VEHICLE v ON s.vehicle_id = v.vehicle_id
WHERE s.service_status = 'Pending';

-- D2. Sort service records by date in descending order
SELECT 
    s.service_id, 
    v.vehicle_number, 
    s.service_type, 
    TO_CHAR(s.service_date, 'YYYY-MM-DD') AS service_date, 
    s.service_status, 
    s.service_cost
FROM SERVICE s
JOIN VEHICLE v ON s.vehicle_id = v.vehicle_id
ORDER BY s.service_date DESC;

-- D3. Search vehicle numbers beginning with 'TN38'
SELECT 
    v.vehicle_id, 
    v.vehicle_number, 
    v.vehicle_type, 
    v.vehicle_model, 
    c.customer_name
FROM VEHICLE v
JOIN CUSTOMER c ON v.customer_id = c.customer_id
WHERE v.vehicle_number LIKE 'TN38%';

-- D4. Retrieve services with costs between ₹2,000 and ₹4,000
SELECT 
    s.service_id, 
    v.vehicle_number, 
    s.service_type, 
    TO_CHAR(s.service_date, 'YYYY-MM-DD') AS service_date, 
    s.service_status, 
    s.service_cost
FROM SERVICE s
JOIN VEHICLE v ON s.vehicle_id = v.vehicle_id
WHERE s.service_cost BETWEEN 2000.00 AND 4000.00
ORDER BY s.service_cost ASC;

-- ============================================================================
-- SECTION E: AGGREGATE FUNCTIONS
-- Total services, total cost, average cost, maximum cost, and minimum cost.
-- ============================================================================
SELECT 
    COUNT(service_id)       AS total_services_count,
    SUM(service_cost)         AS total_service_cost,
    ROUND(AVG(service_cost), 2) AS average_service_cost,
    MAX(service_cost)         AS highest_service_cost,
    MIN(service_cost)         AS lowest_service_cost
FROM SERVICE;

-- ============================================================================
-- SECTION F: GROUPING (GROUP BY)
-- Group services by status; display service count and total revenue per status.
-- ============================================================================
SELECT 
    service_status,
    COUNT(service_id) AS number_of_services,
    SUM(service_cost)   AS total_cost_for_status
FROM SERVICE
GROUP BY service_status
ORDER BY service_status;

-- ============================================================================
-- SECTION G: JOIN QUERY (3-TABLE JOIN)
-- Combine CUSTOMER, VEHICLE, and SERVICE to display comprehensive work order view.
-- Sorted by service_date in descending order.
-- ============================================================================
SELECT 
    c.customer_name,
    v.vehicle_number,
    v.vehicle_model,
    TO_CHAR(s.service_date, 'YYYY-MM-DD') AS service_date,
    s.service_type,
    s.service_status,
    s.service_cost
FROM CUSTOMER c
JOIN VEHICLE v ON c.customer_id = v.customer_id
JOIN SERVICE s ON v.vehicle_id = s.vehicle_id
ORDER BY s.service_date DESC;
